# An operator is a symbol or keyword used to perform an operation on values (called operands).

# Arithmetic Operators

# Operator	Meaning	Example	Output
# +	Addition	10 + 5	15
# -	Subtraction	10 - 5	5
# *	Multiplication	10 * 5	50
# /	Division	10 / 5	2.0
# %	Modulus (remainder)	10 % 3	1
# //	Floor division	10 // 3	3
# **	Power	2 ** 3	8